#!/usr/bin/env python3
"""Deterministic OpenAI-compatible server for workflow integration tests."""

import argparse
import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

VERDICTS = ("likely_dead", "needs_review", "likely_used")


def findings_for(candidates: list[dict]) -> list[dict]:
    """Return one deterministic, schema-valid finding per candidate."""
    findings = []
    for index, candidate in enumerate(candidates):
        verdict = VERDICTS[index % len(VERDICTS)]
        findings.append(
            {
                "node_id": candidate["node_id"],
                "verdict": verdict,
                "confidence": 90 - index,
                "removal_risk": "low" if verdict == "likely_dead" else "medium",
                "reason": f"Deterministic workflow verdict: {verdict}.",
                "evidence": ["Generated by the cross-platform test server."],
            }
        )
    return findings


class FakeLlamaHandler(BaseHTTPRequestHandler):
    """Serve the llama.cpp endpoints used by Reaper."""

    def do_GET(self) -> None:  # noqa: N802
        if self.path == "/health":
            self._send({"status": "ok"})
        elif self.path == "/v1/models":
            self._send({"data": [{"id": "fake-workflow-model"}]})
        else:
            self._send({"error": "not found"}, 404)

    def do_POST(self) -> None:  # noqa: N802
        if self.path != "/v1/chat/completions":
            self._send({"error": "not found"}, 404)
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
            request = json.loads(self.rfile.read(length))
            user_message = next(
                item for item in request["messages"] if item.get("role") == "user"
            )
            candidates = json.loads(user_message["content"])["candidates"]
            content = json.dumps({"findings": findings_for(candidates)})
        except (KeyError, StopIteration, TypeError, ValueError, json.JSONDecodeError):
            self._send({"error": "invalid request"}, 400)
            return
        self._send({"choices": [{"message": {"content": content}}]})

    def log_message(self, format: str, *args: object) -> None:
        return

    def _send(self, payload: object, status: int = 200) -> None:
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def main() -> None:
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080)
    arguments, _ = parser.parse_known_args()
    ThreadingHTTPServer(
        (arguments.host, arguments.port), FakeLlamaHandler
    ).serve_forever()


if __name__ == "__main__":
    main()
